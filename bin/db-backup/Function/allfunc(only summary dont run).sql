CREATE OR REPLACE FUNCTION public.generate_no_order()
 RETURNS text
 LANGUAGE plpgsql
AS $function$
DECLARE
  V_COUNT INTEGER;
  V_TEMP TEXT;
  V_ID_SEQ TEXT;
BEGIN
  V_TEMP:= TO_CHAR(NOW(), 'yyyyMMdd');
  V_ID_SEQ:= CONCAT(V_TEMP,'-ORDER');
  SELECT COUNT(CODE) INTO V_COUNT FROM TABLE_SEQUENCE WHERE CODE = V_ID_SEQ;
  IF V_COUNT = 0 THEN
    INSERT INTO TABLE_SEQUENCE (CODE,VALUE) VALUES (V_ID_SEQ,1);
    RETURN CONCAT(V_TEMP,LPAD(TRIM(TO_CHAR(1,'99999')),5,'0'));
  ELSE
    SELECT VALUE INTO V_COUNT FROM TABLE_SEQUENCE WHERE CODE = V_ID_SEQ;
    UPDATE TABLE_SEQUENCE SET VALUE = VALUE + 1 WHERE CODE = V_ID_SEQ;
    RETURN  CONCAT(V_TEMP,LPAD(TRIM(TO_CHAR(V_COUNT + 1,'99999')),5,'0'));
  END IF;
  COMMIT;
END;
$function$;


CREATE OR REPLACE FUNCTION public.submit_order(source text, aclid text, generaldataorderid numeric, masterofcustomerstatusid numeric, masterofcollateralstatusid numeric, masterofappraisaltypeid numeric, createdbyuserid text, name text, contactpersonname text, contactpersonphone text, notes text, plafondmarketing text, reporttype text, masterofassettypeid numeric, address text, residential_apartement text, clustertower text, block_floor text, number text, rt1 text, rw1 text, zipcode text, region text, district text, city_regency text, province text, totalfile integer, OUT status integer, OUT message text, OUT orderid numeric, OUT orderdetailid numeric)
 RETURNS record
 LANGUAGE plpgsql
AS $function$
DECLARE
	vCount integer := 0;
	vTemp integer := 0;
	V_ID_HEADER BIGINT;
	vState TEXT :='INSERT';
	vJenisAppraisal TEXT := '';
	vBranch NUMERIC;
	vNoOrder TEXT;
BEGIN
	status :=0;
	message := 'Success';
	IF totalfile = 0 THEN
		status :=3;
		message := SAVE_TO_LOG(aclid,source,to_char(status,'0'),'Total file must be greater than 0.');
	ELSE
		SELECT COUNT(ID) INTO vCount from STATUS_NASABAH WHERE ID = masterofcustomerstatusid;
		IF vCount = 0 THEN
			status :=3;
			message := SAVE_TO_LOG(aclid,source,to_char(status,'0'),'Data Master of Customer Status Id Not Valid');
		ELSE
			SELECT COUNT(ID) INTO vCount FROM status_jaminan WHERE ID = masterofcollateralstatusid;
			IF vCount = 0 THEN
				status :=3;
				message := SAVE_TO_LOG(aclid,source,to_char(status,'0'),'Data Master of Collateral Status Id Not Valid');
			ELSE
				SELECT  COUNT(ID) INTO vCount FROM JENIS_APPRAISAL WHERE ID = masterofappraisaltypeid;
				IF vCount = 0 THEN
					status :=3;
					message := SAVE_TO_LOG(aclid,source,to_char(status,'0'),'Data Master of Appraisal Type Id Not Valid');
				ELSE
					SELECT COUNT(user_id) INTO vCount  FROM PERSON WHERE user_id = createdbyuserid;
					IF vCount = 0 THEN
						status :=3;

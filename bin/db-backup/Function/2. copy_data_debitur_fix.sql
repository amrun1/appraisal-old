CREATE OR REPLACE FUNCTION public.copy_data_debitur_fix(
    pidx integer,
    created_by_param character varying,
    collateral_id_param character varying)
  RETURNS integer AS
$BODY$
DECLARE
  VCNT          INT;
  VCNT_SURVEY 	INT;
  VCNT_LPA 		INT;
  VID_UMUM      INT;
  VID_DETAIL    INT;
  VID_DETAIL_OLD INT;
  VRET          INT;
  V_NO_ORDER    VARCHAR;
  VID_LPA_UMUM_NEW	INT;
BEGIN

SELECT COUNT(1) INTO VCNT FROM DATA_UMUM WHERE ID = PIDX;

IF VCNT > 0 THEN
  
  SELECT NEXTVAL('DATA_UMUM_SEQ') INTO VID_UMUM ;
  SELECT GENERATE_NO_ORDER() INTO V_NO_ORDER;
  SELECT ID INTO VID_DETAIL_OLD FROM DATA_DETAIL WHERE ID_DATA_UMUM =  PIDX ;
  SELECT NEXTVAL('LPA_UMUM_SEQ') INTO VID_LPA_UMUM_NEW;
  
  
  INSERT INTO DATA_UMUM 
  (ID, CREATED_BY, CREATED_DATE, UPDATED_BY, MODIFIED_DATE, ADMIN_BY, ADMIN_DATE, CATATAN, CLOSED_BY, CLOSED_DATE, 
   COLLATERAL_ID, NAMA_CONTACT_PERSON, TELP_CONTACT_PERSON, WAKTU, E_FORM_REFF_CODE, NAMA, PLAFOND_MARKETING, POSISI, 
   TASK_LIST, JENIS_LAPORAN, JENIS_APPRAISAL_ID, APPRAISAL_CABANG_ID, STATUS_JAMINAN_ID, STATUS_NASABAH_ID, TL_GROUP_ID, 
   RETENTION, NO_ORDER, SURVEY_BY, SURVEY_DATE, VALUE_BY, VALUE_DATE, ID_KJPP, KATEGORI_APPRAISAL, SOURCE, ID_SOURCE, 
   UPDATED_DATE, CABANG_ID, POSISI_TERAKHIR)
  SELECT VID_UMUM, CREATED_BY_PARAM, NOW()::TIMESTAMP, NULL, NULL, NULL, NULL, CATATAN, NULL, NULL, 
   COLLATERAL_ID_PARAM, NAMA_CONTACT_PERSON, TELP_CONTACT_PERSON, WAKTU, E_FORM_REFF_CODE, NAMA, PLAFOND_MARKETING, 'USER_TL', 
   CREATED_BY_PARAM, JENIS_LAPORAN, JENIS_APPRAISAL_ID, APPRAISAL_CABANG_ID, STATUS_JAMINAN_ID, STATUS_NASABAH_ID, TL_GROUP_ID, 
   RETENTION, V_NO_ORDER , NULL, NULL, NULL, NULL, ID_KJPP, KATEGORI_APPRAISAL, SOURCE, ID_SOURCE, 
   UPDATED_DATE, CABANG_ID, NULL
  FROM DATA_UMUM
  WHERE ID = PIDX;  
  
  SELECT NEXTVAL('DATA_DETAIL_SEQ') INTO VID_DETAIL;
  
  INSERT INTO DATA_DETAIL
  (ID, BLOK_LANTAI, KODE_KOTA, CLUSTER_TOWER, KODE_KECAMATAN, PERUMAHAN_APARTMENT, ALAMAT, NOMOR, KODE_PROPINSI, 
   RT, RW, SLA, STATUS, KODE_KELURAHAN, KODE_POS, KOMPLEK, ID_DATA_UMUM, ID_JENIS_AKTIVA, WAKTU, INPUT_HASIL_SURVEY, 
   KETERANGAN_DROP, STATUS_SURVEY, NAMA, HARGA_JUAL, JUMLAH_LANTAI, LUAS_BANGUNAN, LUAS_TANAH,NAMA_PIC)
  SELECT
   VID_DETAIL, BLOK_LANTAI, KODE_KOTA, CLUSTER_TOWER, KODE_KECAMATAN, PERUMAHAN_APARTMENT, ALAMAT, NOMOR, KODE_PROPINSI, 
   RT, RW, SLA, STATUS, KODE_KELURAHAN, KODE_POS, KOMPLEK, VID_UMUM, ID_JENIS_AKTIVA, WAKTU, INPUT_HASIL_SURVEY, 
   KETERANGAN_DROP, STATUS_SURVEY, NAMA, HARGA_JUAL, JUMLAH_LANTAI, LUAS_BANGUNAN, LUAS_TANAH,NAMA_PIC
    FROM DATA_DETAIL
   WHERE ID_DATA_UMUM =  PIDX ;
  
  INSERT INTO DATA_ATTACT
  (ID, EXT, FILE, NAMA, ID_DATA_DETAIL, ID_JENIS_DOKUMEN)
  SELECT
   NEXTVAL('DATA_ATTACT_SEQ'), EXT, FILE, NAMA, VID_DETAIL, ID_JENIS_DOKUMEN
   FROM DATA_ATTACT
  WHERE ID_DATA_DETAIL = (SELECT ID
    FROM DATA_DETAIL
   WHERE ID_DATA_UMUM = PIDX );
   
 
   
  vret := insert_all_tab_survey_rev1(VID_UMUM,PIDX,VID_DETAIL,VID_DETAIL_OLD,V_NO_ORDER,VID_LPA_UMUM_NEW);
  vret := insert_all_tab_lpa_rev1(VID_UMUM,PIDX,VID_DETAIL,VID_DETAIL_OLD,V_NO_ORDER,VID_LPA_UMUM_NEW);
   
 
  RETURN VID_UMUM;
  COMMIT;  
ELSE
  RETURN  0;
END IF;


  
END;
$BODY$
  LANGUAGE plpgsql VOLATILE
  COST 100;
ALTER FUNCTION public.copy_data_debitur_fix(integer, character varying, character varying)
  OWNER TO postgres;

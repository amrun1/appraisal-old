
CREATE OR REPLACE FUNCTION public.insert_all_tab_survey_rev1(
    p_id_data_umum_new integer,
    p_id_data_umum_old integer,
    p_id_data_detail_new integer,
    p_id_data_detail_old integer,
    p_no_order character varying,
    p_id_lpa_umum_new integer)
  RETURNS integer AS
$BODY$
DECLARE
    VID_SURVEY_UMUM_OLD INT;
	VID_SURVEY_UMUM_NEW INT;
	
	VID_SURVEY_BV_OLD INT;
	VID_SURVEY_BV_NEW INT;
	
	
	VID_SURVEY_MESIN_OLD INT;
	VID_SURVEY_MESIN_NEW INT;
	
	

	
    VID_SURVEY_POINT_OLD INT;
    VID_SURVEY_POINT_NEW INT;
	
	VID_SURVEY_RV_OLD INT;
    VID_SURVEY_RV_NEW INT;
	
	
    VID_SURVEY_BANGUNAN INT;
BEGIN



 
 SELECT ID INTO VID_SURVEY_UMUM_OLD
 FROM survey_umum 
 WHERE id_data_detail = P_ID_DATA_DETAIL_OLD;
 
 SELECT NEXTVAL('SURVEY_UMUM_SEQ') INTO VID_SURVEY_UMUM_NEW;


INSERT INTO survey_umum
(id, catatan, catatan_survey, dihuni, digunakan, ditemui, ditinjau, hasil_survey, image1, image10, image2, image3, image4, image5, image6, image7, image8, image9, jenis_objek, lokasi,
 tanggal, id_data_detail, id_penilaian)
 
 SELECT 
 VID_SURVEY_UMUM_NEW, catatan, catatan_survey, dihuni, digunakan, ditemui, ditinjau, hasil_survey, image1, image10, image2, image3, image4, image5, image6, image7, image8, image9, jenis_objek, lokasi,
 tanggal, P_ID_DATA_DETAIL_NEW, id_penilaian
 FROM survey_umum 
 WHERE id_data_detail = P_ID_DATA_DETAIL_OLD;
 
 
INSERT INTO survey_image
(id, catatan, content_type, image, id_survey_umum, id_lpa, id_laporan_dokumen)
SELECT
NEXTVAL('SURVEY_IMAGE_SEQ'), catatan, content_type, image, VID_SURVEY_UMUM_NEW, P_ID_LPA_UMUM_NEW, id_laporan_dokumen
FROM survey_image
WHERE id_survey_umum = VID_SURVEY_UMUM_OLD;


INSERT INTO survey_kendaraan
(id, bahan_bakar, catatan, kategori, silinder, jenis, kilometer, model, no_mesin, no_polisi, no_rangka, penggunaan, tahun_pembuatan, warna, id_survey_umum, id_data_detail, merk)
select 
 NEXTVAL('SURVEY_KENDARAAN_SEQ'), bahan_bakar, catatan, kategori, silinder, jenis, kilometer, model, no_mesin, no_polisi, no_rangka, penggunaan, tahun_pembuatan, warna, VID_SURVEY_UMUM_NEW, P_ID_DATA_DETAIL_NEW, merk
from survey_kendaraan
where id_data_detail= P_ID_DATA_DETAIL_OLD
and id_survey_umum = VID_SURVEY_UMUM_OLD;




SELECT NEXTVAL('SURVEY_BANGUNAN_SEQ') INTO VID_SURVEY_BANGUNAN;

INSERT INTO SURVEY_BANGUNAN
(ID, JUMLAH_LANTAI, KELAS_BANGUNAN, KONDISI_UMUM, LUAS, PERUNTUKAN, TAHUN_DIBANGUN, 
 TAHUN_RENOVASI, ID_DATA_DETAIL, JENIS_BANGUNAN, JUMLAH_LANTAI_DEPAN, LUAS_LANTAI_1, 
 LUAS_LANTAI_2, LUAS_LANTAI_3, LUAS_LANTAI_4, LUAS_LANTAI_5, HITUNG_MANUAL)
SELECT 
VID_SURVEY_BANGUNAN, JUMLAH_LANTAI, KELAS_BANGUNAN, KONDISI_UMUM, LUAS, PERUNTUKAN, TAHUN_DIBANGUN, 
 TAHUN_RENOVASI, P_ID_DATA_DETAIL_NEW, JENIS_BANGUNAN, JUMLAH_LANTAI_DEPAN, LUAS_LANTAI_1, 
 LUAS_LANTAI_2, LUAS_LANTAI_3, LUAS_LANTAI_4, LUAS_LANTAI_5, HITUNG_MANUAL
 FROM SURVEY_BANGUNAN WHERE ID_DATA_DETAIL = P_ID_DATA_DETAIL_OLD ;


 
 SELECT ID INTO VID_SURVEY_BV_OLD
 FROM SURVEY_BV WHERE ID_DATA_DETAIL = P_ID_DATA_DETAIL_OLD ;
 
 SELECT NEXTVAL('SURVEY_BV_SEQ') INTO VID_SURVEY_BV_NEW;

INSERT INTO SURVEY_BV
(ID, CREATED_BY, CREATED_DATE, UPDATED_BY, UPDATED_DATE, BERTINGKAT, BIDANG_USAHA, 
 DETAIL_OMZET, INFO_S1, INFO_S2, INFO_S3, JALAN_TEMPAT_USAHA, JAM, JENIS_BANGUNAN, 
 JENIS_USAHA, JUMLAH_KARYAWAN, JUMLAH_MOBIL, JUMLAH_MOTOR, JUMLAH_TRUK, KEGIATAN_USAHA, 
 KONDISI_USAHA, LAMA_PENEMPATAN, LINGKUNGAN_SEKITAR, LOKASI_DITEMUKAN, LUAS_BANGUNAN, 
 LUAS_TANAH, MASUK_MOBIL, NOTE, OMZET_PENJUALAN, ADA_PAPAN_NAMA, S1_DITEMUKAN, S1_HUBUNGAN, 
 S1_KELAMIN, S1_KOOPERATIF, S1_NAMA, S2_DITEMUKAN, S2_HUBUNGAN, S2_KELAMIN, S2_KENAL, 
 S2_KOOPERATIF, S2_NAMA, S3_DITEMUKAN, S3_HUBUNGAN, S3_KELAMIN, S3_KENAL, S3_KOOPERATIF, 
 S3_NAMA, STATUS_LOKASI, STATUS_USAHA, SUDAH_PINDAH, DITERIMA_DI, NAMA_VENDOR, ID_DATA_DETAIL)
SELECT 
VID_SURVEY_BV_NEW, CREATED_BY, CREATED_DATE, UPDATED_BY, UPDATED_DATE, BERTINGKAT, BIDANG_USAHA, 
 DETAIL_OMZET, INFO_S1, INFO_S2, INFO_S3, JALAN_TEMPAT_USAHA, JAM, JENIS_BANGUNAN, 
 JENIS_USAHA, JUMLAH_KARYAWAN, JUMLAH_MOBIL, JUMLAH_MOTOR, JUMLAH_TRUK, KEGIATAN_USAHA, 
 KONDISI_USAHA, LAMA_PENEMPATAN, LINGKUNGAN_SEKITAR, LOKASI_DITEMUKAN, LUAS_BANGUNAN, 
 LUAS_TANAH, MASUK_MOBIL, NOTE, OMZET_PENJUALAN, ADA_PAPAN_NAMA, S1_DITEMUKAN, S1_HUBUNGAN, 
 S1_KELAMIN, S1_KOOPERATIF, S1_NAMA, S2_DITEMUKAN, S2_HUBUNGAN, S2_KELAMIN, S2_KENAL, 
 S2_KOOPERATIF, S2_NAMA, S3_DITEMUKAN, S3_HUBUNGAN, S3_KELAMIN, S3_KENAL, S3_KOOPERATIF, 
 S3_NAMA, STATUS_LOKASI, STATUS_USAHA, SUDAH_PINDAH, DITERIMA_DI, NAMA_VENDOR, P_ID_DATA_DETAIL_NEW
 FROM SURVEY_BV WHERE ID_DATA_DETAIL = P_ID_DATA_DETAIL_OLD ;

 
INSERT INTO SURVEYBV_FASILITAS (SURVEYBV_ID, FASILITAS)
SELECT VID_SURVEY_BV_NEW, FASILITAS FROM SURVEYBV_FASILITAS WHERE SURVEYBV_ID = VID_SURVEY_BV_OLD ;

INSERT INTO SURVEYBV_FOTOPADA (SURVEYBV_ID, FOTOPADA)
SELECT VID_SURVEY_BV_NEW, FOTOPADA FROM SURVEYBV_FOTOPADA WHERE SURVEYBV_ID = VID_SURVEY_BV_OLD ;




INSERT INTO SURVEY_LINGKUNGAN
(ID, KEMACETAN, KEPADATAN, SEKITAR, ID_DATA_DETAIL, GSB, GSS, LEBAR_JALAN, KENA_RENCANA_JALAN, DILALUI_RODA_4)
SELECT 
NEXTVAL('SURVEY_LINGKUNGAN_SEQ'), KEMACETAN, KEPADATAN, SEKITAR, P_ID_DATA_DETAIL_NEW, GSB, GSS, LEBAR_JALAN, KENA_RENCANA_JALAN, DILALUI_RODA_4
 FROM SURVEY_LINGKUNGAN WHERE ID_DATA_DETAIL = P_ID_DATA_DETAIL_OLD ;
 
 

 
 SELECT ID INTO VID_SURVEY_MESIN_OLD
 FROM SURVEY_MESIN WHERE ID_DATA_DETAIL = P_ID_DATA_DETAIL_OLD ;
 SELECT NEXTVAL('SURVEY_MESIN_SEQ') INTO VID_SURVEY_MESIN_NEW;
 
INSERT INTO SURVEY_MESIN
(ID, CREATED_BY, CREATED_DATE, UPDATED_BY, UPDATED_DATE, CATATAN, SUKU_CADANG, KONDISI_TEMPAT, 
 LINGKUNGAN_SEKITAR, TEKNISI, TEMPAT_OPERASIONAL, ID_DATA_DETAIL)
SELECT 
NEXTVAL('SURVEY_MESIN_SEQ'), CREATED_BY, CREATED_DATE, UPDATED_BY, UPDATED_DATE, CATATAN, SUKU_CADANG, KONDISI_TEMPAT, 
 LINGKUNGAN_SEKITAR, TEKNISI, TEMPAT_OPERASIONAL, P_ID_DATA_DETAIL_NEW
 FROM SURVEY_MESIN WHERE ID_DATA_DETAIL = P_ID_DATA_DETAIL_OLD ;
 

INSERT INTO SURVEY_MESIN_LAMPIRAN
(ID, ASAL_PEMBUATAN, JENIS_MESIN, JUMLAH_UNIT, KEGUNAAN, KONDISI_MESIN, MERK_MESIN, NO_SERI, 
 WAKTU_PENGGUNAAN, RANGKAIAN_MESIN, TAHUN_PEMBUATAN, TYPE_MESIN, ID_SURVEY_MESIN)
SELECT 
NEXTVAL('SURVEY_MESIN_LAMPIRAN_SEQ'), ASAL_PEMBUATAN, JENIS_MESIN, JUMLAH_UNIT, KEGUNAAN, KONDISI_MESIN, MERK_MESIN, NO_SERI, 
WAKTU_PENGGUNAAN, RANGKAIAN_MESIN, TAHUN_PEMBUATAN, TYPE_MESIN, VID_SURVEY_MESIN_NEW
FROM SURVEY_MESIN_LAMPIRAN WHERE ID_SURVEY_MESIN = VID_SURVEY_MESIN_OLD ;



SELECT ID INTO VID_SURVEY_POINT_OLD
FROM SURVEY_POINT WHERE ID_DATA_DETAIL = P_ID_DATA_DETAIL_OLD;

SELECT NEXTVAL('SURVEY_POINT_SEQ') INTO VID_SURVEY_POINT_NEW;

INSERT INTO SURVEY_POINT
(ID, CATATAN, POSITIF, ID_DATA_DETAIL)
SELECT 
VID_SURVEY_POINT_NEW, CATATAN, POSITIF, P_ID_DATA_DETAIL_NEW
 FROM SURVEY_POINT WHERE ID_DATA_DETAIL = P_ID_DATA_DETAIL_OLD;

INSERT INTO SURVEY_NEGATIF_POINT
(ID_PARAMETER, ID_SURVEY_POINT)
SELECT ID_PARAMETER, VID_SURVEY_POINT_NEW FROM SURVEY_NEGATIF_POINT WHERE ID_SURVEY_POINT = VID_SURVEY_POINT_OLD ;


INSERT INTO SURVEY_PERTIMBANGAN_KHUSUS
(ID_PARAMETER, ID_SURVEY_POINT)
SELECT 
ID_PARAMETER, VID_SURVEY_POINT_NEW
 FROM SURVEY_PERTIMBANGAN_KHUSUS WHERE ID_SURVEY_POINT = VID_SURVEY_POINT_OLD ;

 
 

INSERT INTO SURVEY_PEMBANDING
(ID, ALAMAT, IMAGE, JENIS_OBJECT, KETERANGAN, KONDISI_BANGUNAN, KONDISI_LINGKUNGAN, KONTAK_NAMA, KONTAK_TELP, ID_DATA_DETAIL)
SELECT 
 NEXTVAL('SURVEY_PEMBANDING_SEQ'), ALAMAT, IMAGE, JENIS_OBJECT, KETERANGAN, KONDISI_BANGUNAN, KONDISI_LINGKUNGAN, KONTAK_NAMA, KONTAK_TELP, P_ID_DATA_DETAIL_NEW
 FROM SURVEY_PEMBANDING WHERE ID_DATA_DETAIL = P_ID_DATA_DETAIL_OLD ;

	
 
 
SELECT ID INTO VID_SURVEY_RV_OLD
FROM SURVEY_RV WHERE ID_DATA_DETAIL = P_ID_DATA_DETAIL_OLD;

SELECT NEXTVAL('SURVEY_RV_SEQ') INTO VID_SURVEY_RV_NEW;
 
INSERT INTO SURVEY_RV
(ID, CREATED_BY, CREATED_DATE, UPDATED_BY, UPDATED_DATE, ALAMAT, ADA_CAR_PORT, DIDATANGI_DEBT_COLLECTOR, DIKENAL_NAMA_SAMA, 
 ADA_GARASI, INFO_S1, INFO_S2, INFO_S3, JAM, JENIS_BANGUNAN, KONDISI_RUMAH, LAMA__PENEMPATAN, LINGKUNGAN_SEKITAR, LOKASI_DITEMUKAN, 
 LUAS_BANGUNAN, LUAS_TANAH, NAMA_PANGGILAN, NAMA_PASANGAN, NOTE, PENGHUNI, S1_DITEMUKAN, S1_HUBUNGAN, S1_KELAMIN, S1_KOOPERATIF, 
 S1_NAMA, S2_DITEMUKAN, S2_HUBUNGAN, S2_KELAMIN, S2_KENAL, S2_KOOPERATIF, S2_NAMA, S3_DITEMUKAN, S3_HUBUNGAN, S3_KELAMIN, S3_KENAL, 
 S3_KOOPERATIF, S3_NAMA, STATUS_KEPEMILIKAN, SUDAH_PINDAH, DITERIMA_DI, TELEPON, UMUR, NAMA_VENDOR, ID_DATA_DETAIL)
SELECT 
VID_SURVEY_RV_NEW, CREATED_BY, CREATED_DATE, UPDATED_BY, UPDATED_DATE, ALAMAT, ADA_CAR_PORT, DIDATANGI_DEBT_COLLECTOR, DIKENAL_NAMA_SAMA, 
 ADA_GARASI, INFO_S1, INFO_S2, INFO_S3, JAM, JENIS_BANGUNAN, KONDISI_RUMAH, LAMA__PENEMPATAN, LINGKUNGAN_SEKITAR, LOKASI_DITEMUKAN, 
 LUAS_BANGUNAN, LUAS_TANAH, NAMA_PANGGILAN, NAMA_PASANGAN, NOTE, PENGHUNI, S1_DITEMUKAN, S1_HUBUNGAN, S1_KELAMIN, S1_KOOPERATIF, 
 S1_NAMA, S2_DITEMUKAN, S2_HUBUNGAN, S2_KELAMIN, S2_KENAL, S2_KOOPERATIF, S2_NAMA, S3_DITEMUKAN, S3_HUBUNGAN, S3_KELAMIN, S3_KENAL, 
 S3_KOOPERATIF, S3_NAMA, STATUS_KEPEMILIKAN, SUDAH_PINDAH, DITERIMA_DI, TELEPON, UMUR, NAMA_VENDOR, P_ID_DATA_DETAIL_NEW
 FROM SURVEY_RV WHERE ID_DATA_DETAIL = P_ID_DATA_DETAIL_OLD ;


INSERT INTO SURVEYRV_FOTOPADA (SURVEYRV_ID, FOTOPADA)
SELECT VID_SURVEY_RV_NEW, FOTOPADA FROM SURVEYRV_FOTOPADA WHERE SURVEYRV_ID = VID_SURVEY_RV_OLD ;



INSERT INTO SURVEY_TANAH
(ID, BATAS_BARAT, KESESUAIAN_BATAS, BENTUK, JENIS, KETINGGIAN, KONDISI, KONTUR, LUAS, 
 POSISI, BATAS_SELATAN, BATAS_TIMUR, BATAS_UTARA, ID_DATA_DETAIL)
SELECT 
NEXTVAL('SURVEY_TANAH_SEQ'), BATAS_BARAT, KESESUAIAN_BATAS, BENTUK, JENIS, KETINGGIAN, KONDISI, KONTUR, LUAS, 
 POSISI, BATAS_SELATAN, BATAS_TIMUR, BATAS_UTARA, P_ID_DATA_DETAIL_NEW
 FROM SURVEY_TANAH WHERE ID_DATA_DETAIL = P_ID_DATA_DETAIL_OLD ;



INSERT INTO SURVEY_VESSEL
(ID, CREATED_BY, CREATED_DATE, UPDATED_BY, UPDATED_DATE, GALANGAN, ISI_BERSIH, ISI_KOTOR, KEBANGSAAN, KELAS, 
 KONDISI_UMUM, LEBAR, MANUFAKTUR, MESIN_BACKUP_KAPASITAS_1, MESIN_BACKUP_KAPASITAS_2, MESIN_BACKUP_MERK_1, 
 MESIN_BACKUP_MERK_2, MESIN_BACKUP_NOMOR_1, MESIN_BACKUP_NOMOR_2, MESIN_KAPASITAS_1, MESIN_KAPASITAS_2, 
 MESIN_KAPASITAS_3, MESIN_MERK_1, MESIN_MERK_2, MESIN_MERK_3, MESIN_NOMOR_1, MESIN_NOMOR_2, MESIN_NOMOR_3, 
 NAMA_KAPAL, PANJANG, NAMA_PEMILIK, SELAR, STATUS_AGUNAN, STATUS_JAMINAN, TAHUN, TINGGI, ID_DATA_DETAIL)
SELECT 
NEXTVAL('SURVEY_VESSEL_SEQ'), CREATED_BY, CREATED_DATE, UPDATED_BY, UPDATED_DATE, GALANGAN, ISI_BERSIH, ISI_KOTOR, KEBANGSAAN, KELAS, 
 KONDISI_UMUM, LEBAR, MANUFAKTUR, MESIN_BACKUP_KAPASITAS_1, MESIN_BACKUP_KAPASITAS_2, MESIN_BACKUP_MERK_1, 
 MESIN_BACKUP_MERK_2, MESIN_BACKUP_NOMOR_1, MESIN_BACKUP_NOMOR_2, MESIN_KAPASITAS_1, MESIN_KAPASITAS_2, 
 MESIN_KAPASITAS_3, MESIN_MERK_1, MESIN_MERK_2, MESIN_MERK_3, MESIN_NOMOR_1, MESIN_NOMOR_2, MESIN_NOMOR_3, 
 NAMA_KAPAL, PANJANG, NAMA_PEMILIK, SELAR, STATUS_AGUNAN, STATUS_JAMINAN, TAHUN, TINGGI, P_ID_DATA_DETAIL_NEW
 FROM SURVEY_VESSEL WHERE ID_DATA_DETAIL = P_ID_DATA_DETAIL_OLD ;


RETURN 0;

END;
$BODY$
  LANGUAGE plpgsql VOLATILE
  COST 100;
